export async function createGame() {
  const app = {};
  installInput(app);
  installPlayerActions(app);
  installMelee(app);
  installPlayerFormFlow(app);
  installBossFlow(app);
  installAdventureFlow(app);
  installCheckpoints(app);
  installHud(app);
  installPanels(app);
  installAudio(app);
  installTutorials(app);
  installCollision(app);
  installCamera(app);
  installPrimitives(app);
  installLoop(app);
  installUpdate(app);
  installRender(app);
  setupWorld(app);
  setupRuntime(app);
  bindMenus(app);
  bindInput(app);
  await loadAssets(app);
  exposeSnapshot(app);
  return app;
}
